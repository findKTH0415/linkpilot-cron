'use strict';
/**
 * checkin-rule.test.js — **확인 쪽지가 «굳은 사실»을 나르지 않는다**
 *   〈2026-09-15 사장님 지시: 「오류 발생 · 반복적으로 다시 되돌어옴 · 교차검증 개선해줘」〉.
 *
 * ★★★ [무엇이 났나] 한 시간마다 도는 확인 쪽지에 「지금 막고 있는 것 = PR 합치기」를
 *   **글로 박아** 두었다. 그 뒤 사장님이 합쳐 주셨는데 쪽지는 그대로 남아,
 *   **이미 합쳐진 PR 을 「세 시간째 초안」이라 말하며 같은 것을 또 여쭈었다.**
 *   오류가 한 줄도 안 나고 **사장님만 같은 화면을 다시 보신다.**
 *
 * ★★ [왜 검사가 필요한가] 이것은 코드 고장이 아니라 **내가 글을 쓰는 버릇**이다.
 *   버릇은 문서에만 적으면 반년 뒤에 되돌아온다 (§7 — 사람의 기억에 얹지 않는다).
 *   그래서 **규칙이 CLAUDE.md 에 살아 있는지**를 검사가 지킨다.
 *
 * ★ [재는 것과 못 재는 것] 이 칸이 재는 것은 「규칙이 적혀 있는가」다.
 *   「다음에 내가 그 규칙을 지키는가」는 **여기서 못 잰다** — 그것은 사장님 화면에서만 갈린다.
 *   못 잰 것을 통과로 적지 않는다 (§8).
 */
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const MD = fs.readFileSync(path.join(__dirname, '..', '..', 'CLAUDE.md'), 'utf8');

test('★★★ 「확인 쪽지에 사실을 박지 않는다」가 §7 에 적혀 있다', () => {
  assert.ok(/확인 쪽지에 «사실»을 박지 않는다/.test(MD),
    '되돌아오는 쪽지를 막는 규칙이 CLAUDE.md 에 없다 — 반년 뒤에 같은 일이 난다');
  assert.ok(/반복적으로 다시 되돌어옴/.test(MD),
    '사장님 지시 원문이 안 적혀 있다 — 왜 정했는지가 사라지면 되돌린다 (§7)');
});

test('★★ 무엇을 하라는지까지 적는다 — 「조심하라」로 끝내지 않는다', () => {
  for (const [what, why] of [
    ['«잴 것»만 적는다', '쪽지에 무엇을 적어야 하는지'],
    ['먼저 재고', '깨어나면 재고 나서 말한다는 것'],
    ['delete_trigger', '끝났을 때 지우는 방법'],
    ['두 번까지', '같은 물음의 횟수 한도'],
  ]) {
    assert.ok(MD.indexOf(what) >= 0, why + '가 안 적혀 있다 (「' + what + '」)');
  }
});

test('★★★ 「끝났으면 지운다」를 «다시 안 건다»로 줄여 적지 않았다', () => {
  const i = MD.indexOf('끝났으면 «지운다»');
  assert.ok(i > 0, '지우라는 말이 없다');
  const seg = MD.slice(i, i + 220);
  assert.ok(/다시 걸지 않는 것으로는 모자라다/.test(seg),
    '「다시 안 건다」와 「지운다」를 가르지 않았다 — 이미 걸린 것이 한 번 더 온다');
});

test('★ 남의 세션 쪽지는 «내가 안 지운다»가 함께 적혀 있다', () => {
  assert.ok(/남의 세션 쪽지는 내가 안 지운다/.test(MD),
    '남의 세션 것까지 지우는 길이 열려 있다 — 그 세션이 무엇을 기다리는지 모르게 된다');
});

test('★ 여기서 «못 재는 것»을 적어 둔다', () => {
  console.log('     · 재는 것: 규칙이 CLAUDE.md 에 살아 있는가');
  console.log('     · 못 재는 것: 다음에 내가 그 규칙을 지키는가 — 사장님 화면에서만 갈린다');
  assert.ok(true);
});
